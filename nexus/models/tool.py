"""NEXUS Tool Data Models."""
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
import hashlib
import json


class ToolParameter(BaseModel):
    name: str
    type: str = "string"
    description: str = ""
    required: bool = False
    default: Optional[Any] = None
    enum: Optional[List[Any]] = None
    location: str = "query"  # "path", "query", "body", "header"


class ToolDefinition(BaseModel):
    tool_id: str = Field(..., description="Unique tool identifier")
    name: str = Field(..., description="Human-readable tool name")
    service: str = Field(..., description="High-level service domain (e.g., invoicing, payments, disputes)")
    category: str = Field(..., description="Functional sub-category")
    description: str = Field(..., description="Detailed semantic description of what the tool does")
    method: str = Field(..., description="HTTP Method: GET, POST, PUT, DELETE, PATCH")
    endpoint: str = Field(..., description="URL path template, e.g. /v2/invoicing/invoices/{invoice_id}")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="JSON Schema for parameters")
    request_schema: Dict[str, Any] = Field(default_factory=dict, description="Expected request payload schema")
    permission: str = Field(default="api.execute", description="Required authorization scope")
    risk_level: str = Field(default="LOW", description="Risk classification: HIGH for writes, LOW for reads")
    is_active: bool = Field(default=True, description="Whether the tool is enabled in the registry")
    example_queries: List[str] = Field(default_factory=list, description="5 to 10 example user queries")
    is_generated: bool = Field(default=False, description="Whether example queries were generated by enrichment")
    is_synthetic: bool = Field(default=False, description="Flag for synthetic benchmark distractor tools")
    original_definition: Dict[str, Any] = Field(default_factory=dict, description="Original Postman/OpenAPI definition")

    def content_hash(self) -> str:
        """Compute SHA-256 hash of core content to detect changes for incremental indexing."""
        core_data = {
            "name": self.name,
            "service": self.service,
            "category": self.category,
            "description": self.description,
            "method": self.method,
            "endpoint": self.endpoint,
            "parameters": self.parameters,
            "example_queries": sorted(self.example_queries),
            "is_active": self.is_active,
        }
        serialized = json.dumps(core_data, sort_keys=True)
        return hashlib.sha256(serialized.encode("utf-8")).hexdigest()

    def get_searchable_text(self) -> str:
        """Construct rich semantic text representation for indexing."""
        param_names = []
        if isinstance(self.parameters, dict):
            props = self.parameters.get("properties", {})
            param_names = list(props.keys()) if isinstance(props, dict) else []
            
        parts = [
            f"Tool: {self.name}",
            f"ID: {self.tool_id}",
            f"Service: {self.service}",
            f"Category: {self.category}",
            f"Action: {self.method} {self.endpoint}",
            f"Description: {self.description}",
            f"Parameters: {', '.join(param_names) if param_names else 'None'}",
        ]
        return "\n".join(parts)


class ToolFilter(BaseModel):
    service: Optional[str] = None
    category: Optional[str] = None
    method: Optional[str] = None
    is_active: Optional[bool] = None
    search: Optional[str] = None

